#!/usr/bin/env node
/* =============================================================================
   gen-asset-manifest — inventory system/assets/ for the graphics page
   =============================================================================
   The launcher used to link the assets folder and let the browser render a
   directory listing, which does not work from file:// and tells you nothing
   about what an asset is for. This generates the data the gallery needs.

   Grouping is derived from the filename prefix, which is how the set is
   actually organised (advisor-*, listicles_*, hero-rings-*, tab-*).

     node evals/gen-asset-manifest.js
     node evals/gen-asset-manifest.js --check
   ========================================================================== */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DIR = 'system/assets';
const OUT = 'system/assets/manifest.js';

// Filename prefix -> group + what the group is for. Anything unmatched lands in
// "Other", which is the signal to add a rule here rather than leave it vague.
const GROUPS = [
  [/^logotype|^logomark/,        'Brand marks',    'Wordmark and logomark. The nav inlines its own copies from main.js; these are the exported files.'],
  [/^advisor-/,                  'Advisors',       'Headshots for the Medical Advisory Committee page.'],
  [/^listicles_/,                'Listicle icons', 'Splash Landing listicle module.'],
  [/^hero-rings|^factoid-blob|^closing-blob|^community-feat-panel/, 'Decoration', 'Background shapes for splash and community sections.'],
  [/^tab-/,                      'Nav tab icons',  'Source files for the desktop nav tabs, inlined into main.js with currentColor.'],
  [/^community-/,                'Community',      'Banner and upsell graphics for the community surface.'],
  [/^article-/,                  'Article',        'Imagery for the Article Show surface.'],
  [/^up-/,                       'Level-up icons', 'Per-screen icons for the parked level-up pill.'],
  [/^hub-/,                      'Topic hubs',     'Pre-tinted hub markers.'],
  [/^ai-/,                       'Assistant',      'Ask AI duo-star. main.js builds the gradient version inline; this is the flat export.'],
  [/^placeholder|^privacy/,      'Utility',        'Profile placeholder and the privacy-choices mark.'],
];

function groupOf(name) {
  for (const [re, group, note] of GROUPS) if (re.test(name)) return { group, note };
  return { group: 'Other', note: 'Ungrouped — add a rule in evals/gen-asset-manifest.js.' };
}

const files = fs.readdirSync(path.join(ROOT, DIR))
  .filter(f => /\.(svg|png|jpg|jpeg|webp)$/i.test(f))
  .sort();

const assets = files.map(f => {
  const { group, note } = groupOf(f);
  const bytes = fs.statSync(path.join(ROOT, DIR, f)).size;
  return { file: f, ext: f.split('.').pop().toLowerCase(), bytes, group, note };
});

const groups = [...new Set(assets.map(a => a.group))];
const text = `/* GENERATED by evals/gen-asset-manifest.js — do not edit by hand.
   Source of truth: ${DIR}/
   Regenerate:  node evals/gen-asset-manifest.js
   Verify:      node evals/gen-asset-manifest.js --check

   ${assets.length} assets in ${groups.length} groups. Consumed by ${DIR}/index.html. */
window.MHT_ASSETS = ${JSON.stringify(assets, null, 2)};
`;

const target = path.join(ROOT, OUT);
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (cur !== text) {
    console.error(`FAIL — ${OUT} is out of date. Run: node evals/gen-asset-manifest.js`);
    process.exit(1);
  }
  const ungrouped = assets.filter(a => a.group === 'Other');
  if (ungrouped.length) {
    console.error(`NOTE — ${ungrouped.length} ungrouped asset(s): ${ungrouped.map(a => a.file).join(', ')}`);
  }
  console.log(`PASS — ${OUT} matches ${DIR}/ (${assets.length} assets, ${groups.length} groups).`);
  process.exit(0);
}
fs.writeFileSync(target, text);
console.log(`Wrote ${OUT} — ${assets.length} assets, ${groups.length} groups`);
const ungrouped = assets.filter(a => a.group === 'Other');
if (ungrouped.length) console.error(`\nNOTE — ungrouped: ${ungrouped.map(a => a.file).join(', ')}`);
