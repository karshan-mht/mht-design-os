#!/usr/bin/env node
/* =============================================================================
   gen-component-index — derive the component inventory from the real CSS
   =============================================================================
   There is no component layer to point at yet: styles live in one large
   main.css and behaviour in one large main.js. An index makes them addressable
   without a risky extraction.

   The inventory is GENERATED, not authored, so it cannot drift from the code.
   Only the tier classification below is a human decision.

     node evals/gen-component-index.js          # write the index
     node evals/gen-component-index.js --check  # fail if it is out of date

   The --check mode is what keeps this honest: add a component and forget to
   regenerate, and the check fails.
   ========================================================================== */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CSS = 'prototypes/navigation/main.css';
const JS = 'prototypes/navigation/main.js';
const OUT = 'system/components/INDEX.md';

// The one human judgment here: which tier a block belongs to.
// primitive — small reusable control, the real candidates for extraction
// chrome    — global navigation furniture, one instance per page
// module    — Splash Landing content modules (mod-*)
// surface   — blocks belonging to one product surface
const TIERS = [
  ['primitive', ['icon-btn', 'ai-btn', 'join-btn', 'profile-btn', 'profile-avatar', 'icon',
                 'logo', 'logo-btn', 'logo-accent', 'logo-ink', 'mod-btn-primary',
                 'mod-btn-secondary', 'mod-pill', 'uplevel', 'mod-view-all-link',
                 'mod-carousel-arrow', 'mod-carousel-arrows']],
  ['chrome',    ['nav', 'dnav', 'subnav', 'panel', 'panel-overlay', 'dropdown',
                 'dropdown-overlay', 'footer', 'screen', 'stage', 'phone',
                 'launcher-hotspot', 'flow-close', 'gate', 'gate-overlay']],
];
const PREFIX_TIERS = [['module', 'mod-']];

function tierOf(block) {
  for (const [tier, names] of TIERS) if (names.includes(block)) return tier;
  for (const [tier, prefix] of PREFIX_TIERS) if (block.startsWith(prefix)) return tier;
  return 'surface';
}

function inventory() {
  const css = fs.readFileSync(path.join(ROOT, CSS), 'utf8');
  const js = fs.readFileSync(path.join(ROOT, JS), 'utf8');
  const blocks = new Map();

  const re = /^\s*((?:[.:#][^{,\n]+)(?:,\s*\n?\s*[.:#][^{,\n]+)*)\s*\{/gm;
  for (const m of css.matchAll(re)) {
    for (const sel of m[1].split(',')) {
      const cm = /^\s*\.([a-z][a-z0-9_-]*)/.exec(sel);
      if (!cm) continue;
      const block = cm[1].split(/__|--/)[0];
      const e = blocks.get(block) || { rules: 0, parts: new Set(), variants: new Set() };
      e.rules++;
      const full = cm[1];
      if (full.includes('__')) e.parts.add(full.split('__')[1].split('--')[0]);
      if (full.includes('--')) e.variants.add(full.split('--')[1]);
      blocks.set(block, e);
    }
  }
  // is the block rendered from JS, or only styled?
  for (const [name, e] of blocks) {
    e.inJs = new RegExp(`["'\`\\s]${name}(?:__|--|["'\`\\s])`).test(js);
  }
  return blocks;
}

function render(blocks) {
  const byTier = {};
  for (const [name, e] of blocks) (byTier[tierOf(name)] ||= []).push([name, e]);
  for (const list of Object.values(byTier)) list.sort((a, b) => b[1].rules - a[1].rules);

  // Contracts are flat files: system/components/<block>.md. They used to be
  // <block>/docs.md, one directory per contract — five directories holding one
  // file each, for no gain.
  const dir = path.join(ROOT, 'system/components');
  const contracts = fs.existsSync(dir)
    ? fs.readdirSync(dir)
        .filter(f => f.endsWith('.md') && !['INDEX.md', 'README.md', '_TEMPLATE.md'].includes(f))
        .map(f => f.replace(/\.md$/, ''))
    : [];

  const blurb = {
    primitive: 'Small reusable controls. These are the real candidates for extraction into standalone components.',
    chrome: 'Global navigation furniture — typically one instance per page.',
    module: 'Splash Landing content modules (`mod-*`). Composed, not primitive.',
    surface: 'Blocks belonging to a single product surface. Documented in `product/`, not extracted.',
  };

  let out = `<!-- GENERATED by evals/gen-component-index.js — do not edit by hand.
     Regenerate:  node evals/gen-component-index.js
     Verify:      node evals/gen-component-index.js --check  -->

# Component index

Every CSS block in \`${CSS}\`, derived from the stylesheet itself so it cannot
drift. **Contract** means a \`docs.md\` exists under \`system/components/<name>/\`.

There is no extracted component layer yet — this index is what makes the
monolith addressable in the meantime. See [README.md](README.md) for what the
tiers mean and how to add a contract.

- **${blocks.size}** blocks total
- **${contracts.length}** with a contract
- **JS** = rendered from \`main.js\`; blank = styled only

`;

  for (const tier of ['primitive', 'chrome', 'module', 'surface']) {
    const list = byTier[tier] || [];
    if (!list.length) continue;
    out += `## ${tier} (${list.length})\n\n${blurb[tier]}\n\n`;
    out += `| Block | Rules | Parts | Variants | JS | Contract |\n|---|--:|--:|--:|:-:|:-:|\n`;
    for (const [name, e] of list) {
      const has = contracts.includes(name) ? `[yes](${name}.md)` : '—';
      out += `| \`.${name}\` | ${e.rules} | ${e.parts.size} | ${e.variants.size} | ${e.inJs ? '•' : ''} | ${has} |\n`;
    }
    out += '\n';
  }
  return out;
}

const text = render(inventory());
const target = path.join(ROOT, OUT);

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== text) {
    console.error(`FAIL — ${OUT} is out of date. Run: node evals/gen-component-index.js`);
    process.exit(1);
  }
  console.log(`PASS — ${OUT} matches ${CSS}.`);
  process.exit(0);
}

fs.writeFileSync(target, text);
console.log(`Wrote ${OUT}`);
