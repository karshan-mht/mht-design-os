#!/usr/bin/env node
/* =============================================================================
   gen-token-manifest — derive a token manifest from tokens.css
   =============================================================================
   system/tokens/reference.html used to carry its own parallel vocabulary
   (--action-900, --neutral-700, --reaction-900) with values that had drifted
   from the real layer. A page documenting the tokens should render the tokens,
   not a copy of them.

   This reads system/tokens/tokens.css and emits system/tokens/manifest.js:
   name, the declared value, the group it sits under, and its trailing comment
   as the role description. The page then resolves live values with
   getComputedStyle, so what you see is what the browser actually computes —
   including whatever the loaded theme resolves --brand-* to.

     node evals/gen-token-manifest.js
     node evals/gen-token-manifest.js --check
   ========================================================================== */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = 'system/tokens/tokens.css';
const OUT = 'system/tokens/manifest.js';

const css = fs.readFileSync(path.join(ROOT, SRC), 'utf8');

// Only the base :root block — the media-query override repeats names.
const rootStart = css.indexOf(':root {');
const rootEnd = css.indexOf('\n}', rootStart);
const body = css.slice(rootStart, rootEnd);

const tokens = [];
let group = 'Other';
for (const line of body.split('\n')) {
  const g = line.match(/\/\*\s*-{2,}\s*(.+?)\s*-{2,}\s*\*\//);
  if (g) { group = g[1].trim(); continue; }
  const m = line.match(/^\s*(--[a-z0-9-]+)\s*:\s*([^;]+);\s*(?:\/\*\s*(.*?)\s*\*\/)?/);
  if (!m) continue;
  tokens.push({ name: m[1], value: m[2].trim(), group, note: (m[3] || '').trim() });
}

// Responsive overrides, so the page can show that a token changes at a breakpoint.
const mq = css.slice(rootEnd);
const overrides = [...mq.matchAll(/^\s*(--[a-z0-9-]+)\s*:\s*([^;]+);/gm)].map(m => m[1]);

const text = `/* GENERATED by evals/gen-token-manifest.js — do not edit by hand.
   Source of truth: ${SRC}
   Regenerate:  node evals/gen-token-manifest.js
   Verify:      node evals/gen-token-manifest.js --check

   ${tokens.length} tokens. The declared value is here for reference; the page
   resolves the LIVE value with getComputedStyle, so a themed --brand-* shows
   what the browser actually computes. */
window.MHT_TOKENS = ${JSON.stringify(tokens, null, 2)};
window.MHT_TOKENS_RESPONSIVE = ${JSON.stringify([...new Set(overrides)])};
`;

const target = path.join(ROOT, OUT);
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (cur !== text) {
    console.error(`FAIL — ${OUT} is out of date. Run: node evals/gen-token-manifest.js`);
    process.exit(1);
  }
  console.log(`PASS — ${OUT} matches ${SRC} (${tokens.length} tokens).`);
  process.exit(0);
}
fs.writeFileSync(target, text);
console.log(`Wrote ${OUT} — ${tokens.length} tokens, ${new Set(tokens.map(t => t.group)).size} groups`);
