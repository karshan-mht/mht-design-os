#!/usr/bin/env node
/* =============================================================================
   gen-icon-registry — SVG files in, inline registries out
   =============================================================================
   Two sets, each kept to what the pages actually use:

     system/icons/ui/             UI glyphs: nav, tabs, actions, hub and
                                  level-up markers. 24x24, filled.
     system/icons/illustrations/  Line illustrations: the Splash Landing
                                  listicles and the community feature cards.
                                  Drawn on a 128 grid (one on 99x74).

   The 112-icon editorial line set was removed on 2026-11-16 because no page
   rendered it (it is in git history).

   The files are the source of truth. This generates one registry per set
   (window.MHT_ICONS.ui, window.MHT_ICONS.illustrations), so a page loads only
   the set it uses.

   Why generate an inline registry instead of referencing the .svg files?
   Because <img src="icon.svg"> cannot inherit CSS `color`. Tinting needs the
   SVG inline in the document, and the repo has no build step and must work
   from file://. Generating the registry keeps files authoritative while
   preserving both.

     node evals/gen-icon-registry.js          # write the registries
     node evals/gen-icon-registry.js --check  # fail if one is out of date
   ========================================================================== */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SETS = {
  ui: { dir: 'system/icons/ui', out: 'system/icons/registry-ui.js', what: 'UI glyphs' },
  illustrations: { dir: 'system/icons/illustrations', out: 'system/icons/registry-illustrations.js', what: 'illustrations' },
};

function build(set, { dir, what }) {
  const icons = {};
  for (const f of fs.readdirSync(path.join(ROOT, dir)).sort()) {
    if (!f.endsWith('.svg')) continue;
    icons[f.replace(/\.svg$/, '')] = fs.readFileSync(path.join(ROOT, dir, f), 'utf8')
      .trim()
      .replace(/\s*\n\s*/g, ' ');   // one line per icon keeps the registry diffable
  }
  const keys = Object.keys(icons);
  let text = `/* GENERATED by evals/gen-icon-registry.js — do not edit by hand.
   Source of truth: ${dir}/
   Regenerate:  node evals/gen-icon-registry.js
   Verify:      node evals/gen-icon-registry.js --check

   ${keys.length} ${what}. Keys are the filename without extension, always
   kebab-case. */
window.MHT_ICONS = window.MHT_ICONS || {};
window.MHT_ICONS.${set} = {
`;
  for (const [name, svg] of Object.entries(icons)) {
    text += `  ${/^[a-z][a-z0-9]*$/.test(name) ? name : `"${name}"`}: \`${svg}\`,\n`;
  }
  return { text: text + `};\n`, count: keys.length };
}

const built = Object.fromEntries(Object.entries(SETS).map(([k, v]) => [k, build(k, v)]));
const counts = Object.entries(built).map(([k, b]) => `${b.count} ${SETS[k].what}`).join(', ');

if (process.argv.includes('--check')) {
  const stale = Object.entries(built).filter(([k, b]) => {
    const f = path.join(ROOT, SETS[k].out);
    return !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== b.text;
  });
  if (stale.length) {
    console.error(`FAIL — out of date: ${stale.map(([k]) => SETS[k].out).join(', ')}. Run: node evals/gen-icon-registry.js`);
    process.exit(1);
  }
  console.log(`PASS — icon registries match the files (${counts}).`);
  process.exit(0);
}
for (const [k, b] of Object.entries(built)) fs.writeFileSync(path.join(ROOT, SETS[k].out), b.text);
console.log(`Wrote ${Object.values(SETS).map(s => s.out).join(', ')} — ${counts}`);
