#!/usr/bin/env node
/* =============================================================================
   gen-icon-registry — SVG files in, inline registry out
   =============================================================================
   The repo holds two icon sets with different jobs:

     system/icons/editorial/  112 graphical, detailed icons — symptoms,
                              conditions, life themes. Drawn on a 128px canvas
                              at stroke 3.4, so they are display-sized: below
                              ~44px they render as hairlines.
     system/icons/ui/          28 glyphs for interface chrome — nav, tabs,
                              actions, hub markers.

   Files are the source of truth for both. This generates
   system/icons/registry.js, which the prototype loads before main.js.

   Why generate an inline registry instead of referencing the .svg files?
   Because <img src="icon.svg"> cannot inherit CSS `color`. Tinting needs the
   SVG inline in the document, and the repo has no build step and must work
   from file://. Generating the registry keeps files authoritative while
   preserving both.

     node evals/gen-icon-registry.js          # write the registry
     node evals/gen-icon-registry.js --check  # fail if it is out of date
   ========================================================================== */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SETS = { ui: 'system/icons/ui', editorial: 'system/icons/editorial' };
// One file per set, not one combined registry: the prototype needs only the 28
// UI glyphs, and the 112 editorial icons are ~200KB it would never use.
const OUT = { ui: 'system/icons/registry-ui.js', editorial: 'system/icons/registry-editorial.js' };

function read(dir) {
  const out = {};
  for (const f of fs.readdirSync(path.join(ROOT, dir)).sort()) {
    if (!f.endsWith('.svg')) continue;
    out[f.replace(/\.svg$/, '')] = fs.readFileSync(path.join(ROOT, dir, f), 'utf8')
      .trim()
      .replace(/\s*\n\s*/g, ' ');   // one line per icon keeps the registry diffable
  }
  return out;
}

const sets = Object.fromEntries(Object.entries(SETS).map(([k, d]) => [k, read(d)]));

// Categories are AUTHORED (system/icons/categories.js), not derived — grouping
// is a human judgment. But every editorial icon must appear in exactly one
// category, or the sheet would silently omit it. That part is checkable.
function categoryProblems() {
  const f = path.join(ROOT, 'system/icons/categories.js');
  if (!fs.existsSync(f)) return ['system/icons/categories.js is missing'];
  const sandbox = { window: {} };
  new Function('window', fs.readFileSync(f, 'utf8'))(sandbox.window);
  const cats = sandbox.window.MHT_ICON_CATEGORIES || {};
  const seen = new Map();
  for (const [cat, slugs] of Object.entries(cats))
    for (const s of slugs) seen.set(s, (seen.get(s) || []).concat(cat));

  const problems = [];
  for (const name of Object.keys(sets.editorial))
    if (!seen.has(name)) problems.push(`uncategorised: ${name}.svg`);
  for (const [name, inCats] of seen) {
    if (!sets.editorial[name]) problems.push(`category lists a missing file: ${name}`);
    else if (inCats.length > 1) problems.push(`${name} is in ${inCats.length} categories: ${inCats.join(', ')}`);
  }
  return problems;
}

function build(set, icons) {
  const keys = Object.keys(icons);
  let out = `/* GENERATED by evals/gen-icon-registry.js — do not edit by hand.
   Source of truth: ${SETS[set]}/
   Regenerate:  node evals/gen-icon-registry.js
   Verify:      node evals/gen-icon-registry.js --check

   ${keys.length} ${set} icons. Keys are the filename without extension, always
   kebab-case. icon() converts a camelCase request ("tabHome") to the kebab key,
   so call sites did not have to change when these moved out of main.js.

   Split per set on purpose: the prototype loads only the UI glyphs, and the
   editorial set is ~200KB it would never use. */
window.MHT_ICONS = window.MHT_ICONS || {};
window.MHT_ICONS.${set} = {
`;
  for (const [name, svg] of Object.entries(icons)) {
    out += `  ${/^[a-z][a-z0-9]*$/.test(name) ? name : `"${name}"`}: \`${svg}\`,\n`;
  }
  return out + `};\n`;
}

const built = Object.fromEntries(Object.entries(sets).map(([k, v]) => [k, build(k, v)]));
const counts = Object.entries(sets).map(([k, v]) => `${Object.keys(v).length} ${k}`).join(', ');

const problems = categoryProblems();

if (process.argv.includes('--check')) {
  if (problems.length) {
    console.error(`FAIL — icon category problems:\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  const stale = Object.entries(built).filter(([k, text]) => {
    const f = path.join(ROOT, OUT[k]);
    return !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== text;
  });
  if (stale.length) {
    console.error(`FAIL — out of date: ${stale.map(([k]) => OUT[k]).join(', ')}. Run: node evals/gen-icon-registry.js`);
    process.exit(1);
  }
  console.log(`PASS — icon registries match the files (${counts}).`);
  process.exit(0);
}

for (const [k, text] of Object.entries(built)) fs.writeFileSync(path.join(ROOT, OUT[k]), text);
console.log(`Wrote ${Object.values(OUT).join(', ')} — ${counts}`);
if (problems.length) {
  console.error(`\nWARN — icon category problems:\n  ${problems.join('\n  ')}`);
}
