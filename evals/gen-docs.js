#!/usr/bin/env node
/* =============================================================================
   gen-docs — inline the repo's markdown so the docs viewer can render it
   =============================================================================
   Four launcher sections (Foundations, Brand, Product, Decisions) linked raw
   .md files, which a browser shows as plain text. The fix is one viewer, not
   four bespoke pages.

   The viewer cannot fetch() the files: Chrome blocks that over file://, and
   this repo must work with no server. So the content is generated into a JS
   file, the same approach as the icon registry.

   One file rather than one-per-doc: 21 small scripts in a folder is more
   clutter than a single 330KB payload costs on an internal tool, and it avoids
   dynamic script injection.

     node evals/gen-docs.js
     node evals/gen-docs.js --check
   ========================================================================== */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = 'system/docs/content.js';

// Skipped: generated files (read the source instead) and the viewer's own docs.
const SKIP = new Set(['system/components/INDEX.md']);

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.') && e.name !== '.claude') continue;
    const full = path.join(dir, e.name);
    const rel = path.relative(ROOT, full);
    if (e.isDirectory()) {
      if (['node_modules', 'system/assets', 'system/icons'].includes(rel) || e.name === '.git') continue;
      walk(full, out);
    } else if (e.name.endsWith('.md') && !SKIP.has(rel)) out.push(rel);
  }
  return out;
}

const files = walk(ROOT).sort();

// Title: first H1, else the filename. Inline markdown is stripped — a title
// goes into the nav and the <title>, where `backticks` read as noise.
function titleOf(md, rel) {
  const m = md.match(/^#\s+(.+)$/m);
  if (!m) return path.basename(rel, '.md');
  return m[1].trim().replace(/`/g, '').replace(/\*\*?/g, '').trim();
}

// Which launcher section a doc belongs to, for grouping in the viewer.
function sectionOf(rel) {
  if (rel.startsWith('product/')) return 'Product';
  if (rel.startsWith('decisions/')) return 'Decisions';
  if (rel.startsWith('system/brand/')) return 'Brand';
  if (rel.startsWith('system/components/')) return 'Components';
  if (rel.startsWith('.claude/skills/')) return 'Skills';
  if (rel.startsWith('system/')) return 'Foundations';
  if (rel.startsWith('prototypes/')) return 'Prototypes';
  return 'Root';
}

const docs = files.map(rel => {
  const md = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  return { path: rel, title: titleOf(md, rel), section: sectionOf(rel), bytes: Buffer.byteLength(md), markdown: md };
});

const bySection = {};
docs.forEach(d => { bySection[d.section] = (bySection[d.section] || 0) + 1; });
const total = docs.reduce((n, d) => n + d.bytes, 0);

const text = `/* GENERATED by evals/gen-docs.js — do not edit by hand.
   Regenerate:  node evals/gen-docs.js
   Verify:      node evals/gen-docs.js --check

   ${docs.length} documents, ${(total / 1024).toFixed(0)}KB of markdown, inlined so
   system/docs/index.html can render them without fetch() — which Chrome blocks
   over file://. The .md files remain the source of truth; this is a mirror and
   --check fails when it falls behind. */
window.MHT_DOCS = ${JSON.stringify(docs)};
`;

const target = path.join(ROOT, OUT);
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (cur !== text) {
    console.error(`FAIL — ${OUT} is out of date. Run: node evals/gen-docs.js`);
    process.exit(1);
  }
  console.log(`PASS — ${OUT} matches ${docs.length} markdown files.`);
  process.exit(0);
}
fs.writeFileSync(target, text);
console.log(`Wrote ${OUT} — ${docs.length} docs, ${(total / 1024).toFixed(0)}KB`);
console.log('  ' + Object.entries(bySection).map(([k, v]) => `${k}: ${v}`).join(', '));
